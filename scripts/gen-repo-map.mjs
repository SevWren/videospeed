#!/usr/bin/env node
// gen-repo-map.mjs — Zero-dependency Node ESM script
// Generates docs/ai_generated/REPO_MAP.md from the live file tree.
// Usage:
//   node scripts/gen-repo-map.mjs          — regenerate REPO_MAP.md
//   node scripts/gen-repo-map.mjs --check  — exit non-zero if file is >24 h stale

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'fs';
import { join, relative, resolve } from 'path';

const REPO_ROOT = resolve(new URL('.', import.meta.url).pathname, '..');
const OUTPUT_PATH = join(REPO_ROOT, 'docs', 'ai_generated', 'REPO_MAP.md');
const MANIFEST_PATH = join(REPO_ROOT, 'manifest.json');

const SKIP_DIRS = new Set(['node_modules', '.git', 'dist']);

// ── --check mode ────────────────────────────────────────────────────────────
const CHECK_MODE = process.argv.includes('--check');
if (CHECK_MODE) {
  if (!existsSync(OUTPUT_PATH)) {
    console.error('ERROR: REPO_MAP.md does not exist. Run: node scripts/gen-repo-map.mjs');
    process.exit(1);
  }
  const mtime = statSync(OUTPUT_PATH).mtimeMs;
  const ageMs = Date.now() - mtime;
  const TWENTY_FOUR_HOURS = 24 * 60 * 60 * 1000;
  if (ageMs > TWENTY_FOUR_HOURS) {
    const ageHours = (ageMs / 1000 / 3600).toFixed(1);
    console.error(`ERROR: REPO_MAP.md is ${ageHours}h old (>24h). Run: npm run map:repo`);
    process.exit(1);
  }
  console.log('OK: REPO_MAP.md is up to date.');
  process.exit(0);
}

// ── Helpers ──────────────────────────────────────────────────────────────────
function countLines(filePath) {
  try {
    const content = readFileSync(filePath, 'utf8');
    return content.split('\n').length;
  } catch {
    return 0;
  }
}

function walkDir(dir, results = []) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return results;
  }
  for (const entry of entries) {
    if (SKIP_DIRS.has(entry.name)) {continue;}
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      walkDir(fullPath, results);
    } else if (entry.isFile()) {
      results.push(fullPath);
    }
  }
  return results;
}

// ── Read manifest entry points ───────────────────────────────────────────────
let manifest = {};
try {
  manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
} catch {
  console.error('WARNING: Could not read manifest.json');
}

const entryPoints = new Set();

// Content script
const contentJs = manifest?.content_scripts?.[0]?.js ?? [];
for (const f of contentJs) {entryPoints.add(f);}

// Service worker
if (manifest?.background?.service_worker) {
  entryPoints.add(manifest.background.service_worker);
}

// Options + popup
if (manifest?.options_ui?.page) {entryPoints.add(manifest.options_ui.page);}
if (manifest?.action?.default_popup) {entryPoints.add(manifest.action.default_popup);}

// gif-file-fetcher html is a WAR entry for file:// iframe proxy (D9)
const warResources = manifest?.web_accessible_resources?.[0]?.resources ?? [];
for (const r of warResources) {
  if (!r.includes('*')) {entryPoints.add(r);} // only literal paths, not globs
}

function isEntryPoint(relPath) {
  return entryPoints.has(relPath);
}

// ── Walk tree and group by top-level directory ────────────────────────────────
const allFiles = walkDir(REPO_ROOT);

const groups = {
  'src/': [],
  'tests/': [],
  'docs/': [],
  'scripts/': [],
  '.claude/': [],
  'root': [],
};

for (const absPath of allFiles) {
  const rel = relative(REPO_ROOT, absPath);
  if (rel.startsWith('src/')) {groups['src/'].push(rel);}
  else if (rel.startsWith('tests/')) {groups['tests/'].push(rel);}
  else if (rel.startsWith('docs/')) {groups['docs/'].push(rel);}
  else if (rel.startsWith('scripts/')) {groups['scripts/'].push(rel);}
  else if (rel.startsWith('.claude/')) {groups['.claude/'].push(rel);}
  else if (!rel.includes('/')) {groups['root'].push(rel);}
  // skip CLAUDE/ dir and other top-level dirs not in scope
}

// Sort each group
for (const key of Object.keys(groups)) {
  groups[key].sort();
}

// ── Format table ──────────────────────────────────────────────────────────────
function formatTable(files) {
  if (files.length === 0) {return '_none_\n';}
  const rows = files.map(rel => {
    const absPath = join(REPO_ROOT, rel);
    const loc = countLines(absPath);
    const ep = isEntryPoint(rel) ? ' **[ENTRY]**' : '';
    return `| \`${rel}\` | ${loc}${ep} |`;
  });
  return `| File | LOC |\n|------|-----|\n${  rows.join('\n')  }\n`;
}

// ── Build output ──────────────────────────────────────────────────────────────
const now = new Date().toISOString();
const lines = [];

lines.push('<!-- generated by scripts/gen-repo-map.mjs — do not edit by hand -->');
lines.push('<!-- regenerate: npm run map:repo -->');
lines.push('<!-- check staleness: node scripts/gen-repo-map.mjs --check -->');
lines.push('');
lines.push('# REPO_MAP');
lines.push('');
lines.push(`**Generated**: ${now}`);
lines.push('');
lines.push('**[ENTRY]** = loaded directly by the browser (manifest.json entry point or web_accessible_resource literal path).');
lines.push('');
lines.push('For module roles and invariants, see `docs/ai_generated/modules/` cards.');
lines.push('For protected behaviors (P1-P14), see `docs/ai_generated/protected-behaviors/registry.md`.');
lines.push('For seam contracts, see `docs/ai_generated/SEAM-INDEX.md`.');
lines.push('');

const groupLabels = {
  'src/': '## src/ — Extension source',
  'tests/': '## tests/ — Test suite',
  'docs/': '## docs/ — AI-generated documentation',
  'scripts/': '## scripts/ — Tooling scripts',
  '.claude/': '## .claude/ — Agent skill definitions',
  'root': '## Root files',
};

for (const [key, label] of Object.entries(groupLabels)) {
  lines.push(label);
  lines.push('');
  lines.push(formatTable(groups[key]));
}

// Summary
const totalFiles = Object.values(groups).reduce((sum, arr) => sum + arr.length, 0);
const totalLoc = Object.values(groups)
  .flat()
  .reduce((sum, rel) => sum + countLines(join(REPO_ROOT, rel)), 0);

lines.push('---');
lines.push('');
lines.push(`**Total tracked files in map**: ${totalFiles}  `);
lines.push(`**Total LOC in map**: ${totalLoc}  `);
lines.push(`**Entry points (manifest)**: ${entryPoints.size}`);
lines.push('');

const output = lines.join('\n');
writeFileSync(OUTPUT_PATH, output, 'utf8');
console.log(`Written: ${OUTPUT_PATH}`);
console.log(`Files mapped: ${totalFiles}, LOC: ${totalLoc}`);
