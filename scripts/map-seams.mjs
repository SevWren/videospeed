#!/usr/bin/env node
// map-seams.mjs — Zero-dependency Node ESM script
// Generates docs/ai_generated/seams/SEAM-MAP.generated.md from *.seam.md cards.
// Usage:
//   node scripts/map-seams.mjs          — regenerate SEAM-MAP.generated.md
//   node scripts/map-seams.mjs --check  — exit non-zero if file is >24 h stale

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'fs';
import { join, resolve } from 'path';

const REPO_ROOT = resolve(new URL('.', import.meta.url).pathname, '..');
const SEAMS_DIR = join(REPO_ROOT, 'docs', 'ai_generated', 'seams');
const SEAM_INDEX_PATH = join(REPO_ROOT, 'docs', 'ai_generated', 'SEAM-INDEX.md');
const OUTPUT_PATH = join(SEAMS_DIR, 'SEAM-MAP.generated.md');

// ── --check mode ─────────────────────────────────────────────────────────────
const CHECK_MODE = process.argv.includes('--check');
if (CHECK_MODE) {
  if (!existsSync(OUTPUT_PATH)) {
    console.error('ERROR: SEAM-MAP.generated.md does not exist. Run: node scripts/map-seams.mjs');
    process.exit(1);
  }
  const mtime = statSync(OUTPUT_PATH).mtimeMs;
  const ageMs = Date.now() - mtime;
  const TWENTY_FOUR_HOURS = 24 * 60 * 60 * 1000;
  if (ageMs > TWENTY_FOUR_HOURS) {
    const ageHours = (ageMs / 1000 / 3600).toFixed(1);
    console.error(
      `ERROR: SEAM-MAP.generated.md is ${ageHours}h old (>24h). Run: npm run map:seams`
    );
    process.exit(1);
  }
  console.log('OK: SEAM-MAP.generated.md is up to date.');
  process.exit(0);
}

// ── Read seam cards ───────────────────────────────────────────────────────────
function readSeamCards(seamsDir) {
  if (!existsSync(seamsDir)) {
    return [];
  }
  const files = readdirSync(seamsDir).filter(
    (f) => f.endsWith('.seam.md') && f !== 'SEAM-MAP.generated.md'
  );
  return files.map((filename) => {
    const filePath = join(seamsDir, filename);
    const src = readFileSync(filePath, 'utf8');
    return { filename, src };
  });
}

// ── Parse a seam card for summary fields ─────────────────────────────────────
function parseSeamCard(filename, src) {
  const name = filename.replace('.seam.md', '');

  // Extract File: reference — handles bold, backtick, and plain formats
  let file = null;
  const fileMatch =
    src.match(/\*\*File\*\*:\s*`([^`]+)`/) ||
    src.match(/File:\s*`([^`]+)`/) ||
    src.match(/File:\s*(\S+\.js)/) ||
    src.match(/\|\s*File\s*\|\s*`([^`]+)`/);
  if (fileMatch) {
    file = fileMatch[1];
  }

  // Extract LOC
  let loc = null;
  const locMatch = src.match(/\*\*LOC\*\*:\s*(\d+)/);
  if (locMatch) {
    loc = parseInt(locMatch[1], 10);
  }

  // Extract World
  let world = null;
  const worldMatch = src.match(/\*\*World\*\*:\s*([^\n]+)/);
  if (worldMatch) {
    world = worldMatch[1].trim();
  }

  // Extract window.VSC registration
  let registration = null;
  const regMatch = src.match(/\*\*window\.VSC registration\*\*:\s*([^\n]+)/);
  if (regMatch) {
    registration = regMatch[1].trim();
  }

  // Extract Protected Behaviors listed
  const pbs = [];
  const pbMatches = src.matchAll(/\|\s*(P\d+[^|]*)\s*\|/g);
  const pbSet = new Set();
  for (const m of pbMatches) {
    const pb = m[1].trim().match(/^(P\d+)/);
    if (pb && !pbSet.has(pb[1])) {
      pbSet.add(pb[1]);
      pbs.push(pb[1]);
    }
  }

  return { name, file, loc, world, registration, pbs };
}

// ── Read SEAM-INDEX for module-count and date ─────────────────────────────────
function readSeamIndex(indexPath) {
  if (!existsSync(indexPath)) {
    return { moduleCount: null, date: null };
  }
  const src = readFileSync(indexPath, 'utf8');
  const moduleCountMatch = src.match(/^module-count:\s*(\d+)/m);
  const dateMatch = src.match(/^date:\s*(\S+)/m);
  return {
    moduleCount: moduleCountMatch ? parseInt(moduleCountMatch[1], 10) : null,
    date: dateMatch ? dateMatch[1] : null,
  };
}

// ── Generate the map ──────────────────────────────────────────────────────────
const cards = readSeamCards(SEAMS_DIR);
const { moduleCount, date: indexDate } = readSeamIndex(SEAM_INDEX_PATH);
const now = new Date().toISOString().slice(0, 10);

// Sort cards alphabetically by name
cards.sort((a, b) => a.filename.localeCompare(b.filename));

const parsed = cards.map(({ filename, src }) => parseSeamCard(filename, src));

// Build table rows
const tableRows = parsed.map((card) => {
  const file = card.file ? `\`${card.file}\`` : '—';
  const loc = card.loc !== null ? String(card.loc) : '—';
  const pbs = card.pbs.length > 0 ? card.pbs.join(', ') : '—';
  return `| [${card.name}](${card.name}.seam.md) | ${file} | ${loc} | ${pbs} |`;
});

const output = [
  `<!-- DO NOT EDIT — generated by scripts/map-seams.mjs on ${now} -->`,
  '# SEAM-MAP',
  '',
  'Generated summary of all seam cards under `docs/ai_generated/seams/`.',
  'Source of truth: individual `*.seam.md` files. SEAM-INDEX: `docs/ai_generated/SEAM-INDEX.md`.',
  '',
  `**Cards found**: ${parsed.length}${moduleCount !== null ? ` / ${moduleCount} modules in SEAM-INDEX` : ''}`,
  `**Generated**: ${now}${indexDate ? ` | SEAM-INDEX date: ${indexDate}` : ''}`,
  '',
  '---',
  '',
  '## Seam Cards',
  '',
  '| Module | File | LOC | Protected Behaviors |',
  '|--------|------|-----|---------------------|',
  ...tableRows,
  '',
  '---',
  '',
  '## Coverage',
  '',
  '| Metric | Value |',
  '|--------|-------|',
  `| Seam cards present | ${parsed.length} |`,
  `| Total modules in SEAM-INDEX | ${moduleCount !== null ? moduleCount : '(SEAM-INDEX not found)'} |`,
  `| Protected behaviors covered | ${[...new Set(parsed.flatMap((c) => c.pbs))].sort().join(', ') || '—'} |`,
  '',
  '*Re-generate with `npm run map:seams`. Check staleness with `node scripts/map-seams.mjs --check`.*',
].join('\n');

writeFileSync(OUTPUT_PATH, output, 'utf8');
console.log(`Generated: ${OUTPUT_PATH}`);
console.log(`  ${parsed.length} seam cards mapped.`);
